				Panel val3 = (Panel)GetControlByName((Control)(object)parent, "ItemContainer");
				((WebControl)val3).CssClass = "ItemContainer";
			}
			Panel val4 = (Panel)GetControlByName((Control)(object)e.Item, "ItemContainer");
			Panel val5;
			((WebControl)(val5 = val4)).CssClass = ((WebControl)val5).CssClass + " ItemSelected";
			IdFilterChoice.Value = ((CommandEventArgs)e).CommandArgument.ToString();
			if (Operators.CompareString(((CommandEventArgs)e).CommandName, "L", false) == 0)
			{
				btnConferma_Click(btnConferma, new EventArgs());
			}
			val = (FXRETURN)0;
		}
		catch (Exception ex)
		{
			ProjectData.SetProjectError(ex);
			Exception objEx = ex;
			val = HandleError(ref objEx, ref rsMess);
			ProjectData.ClearProjectError();
		}
		finally
		{
			CallStackRemove();
			if ((int)val > 0)
			{
				WriteErrorMessage(rsMess);
			}
		}
	}
