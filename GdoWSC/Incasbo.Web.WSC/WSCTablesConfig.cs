namespace Incasbo.Web.WSC;

public class WSCTablesConfig
{
	public string SessionTable { get; set; }

	public string EventLogTable { get; set; }

	public string UserTable { get; set; }

	public WSCTablesConfig()
	{
		string sessionTable = "";
		SessionTable = sessionTable;
		sessionTable = "";
		EventLogTable = sessionTable;
		sessionTable = "";
		UserTable = sessionTable;
	}
}
