namespace Incasbo.Web.WSC;

public class WSCApplicationConfig
{
	public string LogoApplicazione { get; set; }

	public string LogoDitta { get; set; }

	public string LogoIncas { get; set; }

	public string TitoloApplicazione { get; set; }

	public string InfoIncas { get; set; }

	public string TitoloModuloSoftware { get; set; }

	public string TitoloModuloSoftwareAcronimo { get; set; }

	public WSCApplicationConfig()
	{
		string logoApplicazione = "";
		LogoApplicazione = logoApplicazione;
		logoApplicazione = "";
		LogoDitta = logoApplicazione;
		logoApplicazione = "";
		LogoIncas = logoApplicazione;
		logoApplicazione = "";
		TitoloApplicazione = logoApplicazione;
		logoApplicazione = "";
		InfoIncas = logoApplicazione;
		logoApplicazione = "";
		TitoloModuloSoftware = logoApplicazione;
		logoApplicazione = "";
		TitoloModuloSoftwareAcronimo = logoApplicazione;
	}
}
